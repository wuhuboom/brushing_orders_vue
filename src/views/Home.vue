<script>
import HomeHeader from "@/components/HomeHeader.vue";
import HomeFooter from "@/components/HomeFooter.vue";

function scrollProgress(element, viewportShare) {
  // Read layout offsets so the translated target does not affect its own progress.
  if (!element.offsetParent) return 0;
  let top = 0;
  for (let node = element; node; node = node.offsetParent) {
    top += node.offsetTop;
  }
  return Math.min(1, Math.max(0, (top - window.scrollY) / (window.innerHeight * viewportShare)));
}

export default {
  name: "HomePage",
  components: { HomeHeader, HomeFooter },
  mounted() {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    this.revealObserver = new IntersectionObserver((entries) => {
      entries.forEach(({ target, isIntersecting }) => {
        if (!isIntersecting) return;
        target.setAttribute("data-enter", target.getAttribute("data-scroll-enter"));
        this.revealObserver.unobserve(target);
      });
    });
    this.$el
      .querySelectorAll("[data-scroll-enter]")
      .forEach((element) => this.revealObserver.observe(element));
    this.updateScroll();
    window.addEventListener("scroll", this.queueScrollUpdate, { passive: true });
    window.addEventListener("resize", this.queueScrollUpdate);
    document.fonts.ready.then(() => {
      if (this.revealObserver) this.queueScrollUpdate();
    });
  },
  beforeDestroy() {
    if (this.revealObserver) this.revealObserver.disconnect();
    this.revealObserver = null;
    cancelAnimationFrame(this.scrollFrame);
    window.removeEventListener("scroll", this.queueScrollUpdate);
    window.removeEventListener("resize", this.queueScrollUpdate);
  },
  methods: {
    skipToContent() {
      const main = this.$refs.main;
      main.focus({ preventScroll: true });
      main.scrollIntoView();
    },
    queueScrollUpdate() {
      if (!this.scrollFrame) this.scrollFrame = requestAnimationFrame(this.updateScroll);
    },
    updateScroll() {
      this.scrollFrame = null;
      const { heroArt, workScript, processLine } = this.$refs;
      const hero = scrollProgress(heroArt, 1);
      heroArt.style.transform = `translateY(${-160 * hero}px) rotate(${-8 * hero}deg)`;
      workScript.style.transform = `translateX(${-700 * scrollProgress(workScript, 1)}px)`;
      processLine.style.transform = `scaleX(${scrollProgress(processLine, 0.6)})`;
    },
  },
};
</script>
