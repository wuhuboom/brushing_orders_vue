<script>
import HomeHeader from "@/components/HomeHeader.vue";
import HomeFooter from "@/components/HomeFooter.vue";
import Swiper from "@/vendor/swiper.min.js";
import lottie from "@/vendor/lottie.min.js";
import rocket from "@/assets/rocket.json";
import entrances from "@/assets/entrance-animations.json";

export default {
  name: "HomePage",
  components: { HomeHeader, HomeFooter },
  data: () => ({ showBackToTop: false, loaderClose: false }),
  mounted() {
    this.sliders = [];
    this.animations = [];
    this.observers = [];
    this.setupCarousels();
    this.setupAnimations();
    this.rocketAnimation = lottie.loadAnimation({
      container: this.$refs.rocket,
      renderer: "svg",
      loop: true,
      autoplay: false,
      animationData: rocket,
    });
    const rocketObserver = new IntersectionObserver(([entry]) => {
      if (entry.isIntersecting) this.rocketAnimation.play();
      else this.rocketAnimation.pause();
    }, { rootMargin: "0px 0px -20% 0px" });
    rocketObserver.observe(this.$refs.rocket);
    this.observers.push(rocketObserver);
    this.updateScroll();
    window.addEventListener("scroll", this.updateScroll, { passive: true });
    window.addEventListener("load", this.finishLoading, { once: true });
    this.loaderTimer = setTimeout(() => { this.loaderClose = true; }, 15000);
    if (document.readyState === "complete") this.finishLoading();
    document.fonts.ready.then(() => {
      if (this._isDestroyed) return;
      this.sliders.forEach(slider => slider.update());
      this.finishLoading();
    });
  },
  beforeDestroy() {
    this.observers.forEach(observer => observer.disconnect());
    this.animations.forEach(animation => animation.cancel());
    this.sliders.forEach(slider => slider.destroy(true, true));
    this.rocketAnimation.destroy();
    clearTimeout(this.loaderTimer);
    window.removeEventListener("scroll", this.updateScroll);
    window.removeEventListener("load", this.finishLoading);
  },
  methods: {
    goToWork() {
      // Keep the same destination calculation as public/redirect.js.
      const host = window.location.host.replace(/^(?:(?:work|www)\.)+/i, "");
      window.location.assign(window.location.protocol + "//work." + host + "/");
    },
    finishLoading() {
      document.body.classList.add("loaded");
    },
    updateScroll() {
      this.showBackToTop = window.scrollY > 800;
    },
    backToTop() {
      window.scrollTo({ top: 0, behavior: "smooth" });
    },
    setupCarousels() {
      const testimonial = this.$el.querySelector(".dsm_card_carousel_wrapper");
      const testimonialModule = testimonial.parentElement;
      this.sliders.push(new Swiper(testimonial, {
        speed: 300,
        loop: true,
        slidesPerView: 1,
        spaceBetween: 20,
        grabCursor: true,
        autoHeight: false,
        resizeObserver: false,
        a11y: { enabled: true },
        navigation: {
          nextEl: testimonialModule.querySelector(".swiper-button-next"),
          prevEl: testimonialModule.querySelector(".swiper-button-prev"),
        },
        pagination: {
          el: testimonialModule.querySelector(".swiper-pagination"),
          clickable: true,
        },
      }));
      const articles = this.$el.querySelector(".dsm_blog_carousel_wrapper");
      const articleModule = articles.closest(".dsm-blog-carousel");
      const blog = new Swiper(articles, {
        speed: 500,
        loop: true,
        autoHeight: true,
        slidesPerView: 1,
        spaceBetween: 30,
        grabCursor: true,
        slideClass: "dsm-blog-carousel-item",
        wrapperClass: "dsm-blog-carousel-wrapper",
        setWrapperSize: true,
        breakpoints: { 768: { slidesPerView: 2 }, 981: { slidesPerView: 3 } },
        navigation: {
          nextEl: articleModule.querySelector(".dsm-arrow-button-next0"),
          prevEl: articleModule.querySelector(".dsm-arrow-button-prev0"),
        },
        pagination: {
          el: articleModule.querySelector(".dsm-pagination0"),
          clickable: true,
        },
        autoplay: { enabled: false, delay: 5000, disableOnInteraction: false },
      });
      this.sliders.push(blog);
      const observer = new IntersectionObserver(([entry]) => {
        if (entry.isIntersecting) { blog.autoplay.start(); observer.disconnect(); }
      }, { rootMargin: "0px 0px -20% 0px" });
      observer.observe(articles);
      this.observers.push(observer);
    },
    setupAnimations() {
      if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
      const settings = new Map();
      entrances.forEach(config => {
        const target = this.$el.querySelector("." + config.class);
        if (!target) return;
        const element = target.closest(".et_pb_button_module_wrapper") || target;
        element.style.opacity = "0";
        settings.set(element, config);
      });
      const observer = new IntersectionObserver(entries => {
        entries.forEach(({ target, isIntersecting }) => {
          if (!isIntersecting || !target.getClientRects().length) return;
          const config = settings.get(target);
          const suffix = window.innerWidth <= 767 ? "_phone" : window.innerWidth <= 980 ? "_tablet" : "";
          const style = config["style" + suffix] || config.style;
          const intensity = parseInt(config.intensity, 10);
          let transform = "none";
          if (style === "slideTop") transform = `translate3d(0, ${-2 * intensity}%, 0)`;
          if (style === "slideBottom") transform = `translate3d(0, ${2 * intensity}%, 0)`;
          if (style === "slideLeft") transform = `translate3d(${-2 * intensity}%, 0, 0)`;
          if (style === "slideRight") transform = `translate3d(${2 * intensity}%, 0, 0)`;
          if (style === "slide" || style === "zoom") transform = `scale3d(${1 - intensity / 100}, ${1 - intensity / 100}, ${1 - intensity / 100})`;
          if (style === "fold") transform = `perspective(2000px) rotateY(${-Math.ceil(0.9 * intensity)}deg)`;
          const animation = target.animate([
            { opacity: parseInt(config.starting_opacity, 10) / 100, transform },
            { opacity: 1, transform: "none" },
          ], {
            duration: parseInt(config.duration, 10),
            delay: parseInt(config.delay, 10),
            easing: config.speed_curve,
            fill: "both",
          });
          animation.onfinish = () => { target.style.opacity = ""; animation.cancel(); };
          this.animations.push(animation);
          observer.unobserve(target);
        });
      });
      settings.forEach((_, element) => observer.observe(element));
      this.observers.push(observer);
      const imageObserver = new IntersectionObserver(entries => {
        entries.forEach(({target, isIntersecting}) => {
          if (!isIntersecting) return;
          target.classList.add("et-animated");
          imageObserver.unobserve(target);
        });
      });
      this.$el.querySelectorAll(".et-waypoint:not(.et_pb_animation_off)").forEach(image => {
        image.classList.remove("et-animated");
        imageObserver.observe(image);
      });
      this.observers.push(imageObserver);
    },
  },
};
</script>
