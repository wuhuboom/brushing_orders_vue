<script>
import HomeHeader from "@/components/HomeHeader.vue";
import HomeFooter from "@/components/HomeFooter.vue";

export default {
  name: "HomePage",
  components: { HomeHeader, HomeFooter },
  data: () => ({ slideIndex: 0, playingPreviews: {} }),
  mounted() {
    const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    this.reveals = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-revealed");
        this.reveals.unobserve(entry.target);
      });
    }, { rootMargin: "0px 0px -5% 0px", threshold: 0 });
    this.$el.querySelectorAll("[data-reveal]:not([data-load])").forEach((element) => {
      if (reducedMotion) element.classList.add("is-revealed");
      else this.reveals.observe(element);
    });
    if (document.readyState === "complete") this.playHero();
    else window.addEventListener("load", this.playHero, { once: true });
  },
  beforeDestroy() {
    this.reveals.disconnect();
    clearTimeout(this.heroTimeout);
    window.removeEventListener("load", this.playHero);
  },
  methods: {
    playHero() {
      if (navigator.connection && navigator.connection.saveData) return;
      this.heroTimeout = setTimeout(() => {
        this.$refs.heroVideo.muted = true;
        this.$refs.heroVideo.play().catch(() => {});
      }, 250);
    },
    playPreview(event) {
      event.currentTarget.querySelector("video").play().catch(() => {});
    },
    pausePreview(event, index) {
      const video = event.currentTarget.querySelector("video");
      video.pause();
      video.currentTime = 0;
      this.$set(this.playingPreviews, index, false);
    },
  },
};
</script>
