<script setup>
import { onBeforeUnmount, onMounted, ref } from "vue";
import { RouterLink } from "vue-router";
import animations from "./psg-home-animations.json";
import "./psg-reference.css";
import "./wester-marketing.css";

const content = ref(null);
const heroVideo = ref(null);
const rocket = ref(null);
let disposed = false;
let reveal;
let reviewsReveal;
let rocketAnimation;
let resize;
const sliders = [];
const effects = [];
const animationConfig = new WeakMap();

function loadLibrary(src, name) {
  if (window[name]) return Promise.resolve(window[name]);
  return new Promise((resolve, reject) => {
    const script = document.createElement("script");
    script.src = src;
    script.onload = () => resolve(window[name]);
    script.onerror = reject;
    document.head.appendChild(script);
  });
}

onMounted(async () => {
  const root = content.value;
  const scrollport = root.closest(".wm-page-scroll");
  reveal = new IntersectionObserver(
    (entries) => {
      for (const entry of entries) {
        if (!entry.isIntersecting) continue;
        const config = animationConfig.get(entry.target);
        const style = config.style_phone || config.style_tablet || config.style;
        const intensity = parseFloat(config.intensity);
        const from = {
          opacity: Number.parseFloat(config.starting_opacity) / 100,
        };
        if (style === "slideLeft")
          from.transform = `translateX(${-2 * intensity}%)`;
        if (style === "slideRight")
          from.transform = `translateX(${2 * intensity}%)`;
        if (style === "slideBottom")
          from.transform = `translateY(${2 * intensity}%)`;
        if (style === "zoom" || style === "slide")
          from.transform = `scale(${1 - intensity / 100})`;
        if (style === "fold")
          from.transform = `perspective(2000px) rotateY(${-Math.ceil(0.9 * intensity)}deg)`;
        entry.target.style.removeProperty("opacity");
        effects.push(
          entry.target.animate([from, { opacity: 1, transform: "none" }], {
            duration: parseInt(config.duration),
            delay: parseInt(config.delay),
            easing: config.speed_curve,
            fill: "backwards",
          }),
        );
        reveal.unobserve(entry.target);
      }
    },
    { root: scrollport },
  );
  for (const config of animations) {
    for (const element of root.getElementsByClassName(config.class)) {
      const target = element.matches("a.et_pb_button")
        ? element.parentElement
        : element;
      animationConfig.set(target, config);
      target.style.opacity = "0";
      reveal.observe(target);
    }
  }
  heroVideo.value.muted = true;
  heroVideo.value.play().catch(() => {});

  const [lottie, Swiper] = await Promise.all([
    loadLibrary("/psg-home/lottie.min.js", "lottie"),
    loadLibrary("/psg-home/swiper.min.js", "Swiper"),
  ]);
  if (disposed) return;
  rocketAnimation = lottie.loadAnimation({
    container: rocket.value,
    renderer: "svg",
    loop: true,
    autoplay: true,
    path: "/psg-home/rocket.json",
  });
  const reviews = root.querySelector(".dsm_card_carousel");
  const navigationHeight = root
    .closest(".bp-home-page")
    .querySelector(".das-footer").offsetHeight;
  reviewsReveal = new IntersectionObserver(
    (entries) => {
      if (!entries.some((entry) => entry.isIntersecting)) return;
      reviews.classList.add("is-in-view");
      reviewsReveal.disconnect();
    },
    { root: scrollport, rootMargin: `0px 0px -${navigationHeight}px 0px` },
  );
  reviewsReveal.observe(reviews);
  sliders.push(
    new Swiper(reviews.querySelector(".swiper-container"), {
      slidesPerView: 1,
      slidesPerGroup: 1,
      spaceBetween: 20,
      speed: 300,
      loop: true,
      grabCursor: true,
      autoHeight: true,
      navigation: {
        prevEl: reviews.querySelector(".swiper-button-prev"),
        nextEl: reviews.querySelector(".swiper-button-next"),
      },
      pagination: {
        el: reviews.querySelector(".swiper-pagination"),
        clickable: true,
      },
    }),
  );
  const articles = root.querySelector(".dsm_blog_carousel");
  sliders.push(
    new Swiper(articles.querySelector(".swiper-container"), {
      slidesPerView: 1,
      slidesPerGroup: 1,
      spaceBetween: 30,
      speed: 500,
      loop: true,
      allowTouchMove: false,
      grabCursor: true,
      autoHeight: true,
      autoplay: { delay: 5000, disableOnInteraction: false },
      navigation: {
        prevEl: articles.querySelector(".swiper-button-prev"),
        nextEl: articles.querySelector(".swiper-button-next"),
      },
      pagination: {
        el: articles.querySelector(".swiper-pagination"),
        clickable: true,
      },
    }),
  );
  resize = new ResizeObserver(() => {
    const width = root.clientWidth;
    const blog = sliders[1];
    blog.params.slidesPerView = width > 980 ? 3 : width > 767 ? 2 : 1;
    for (const slider of sliders) slider.update();
  });
  resize.observe(root);
});

onBeforeUnmount(() => {
  disposed = true;
  reveal?.disconnect();
  reviewsReveal?.disconnect();
  resize?.disconnect();
  effects.forEach((effect) => effect.cancel());
  rocketAnimation?.destroy();
  sliders.forEach((slider) => slider.destroy(true, true));
  heroVideo.value?.pause();
});
</script>
